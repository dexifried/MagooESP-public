"""Build the versioned Music screen package carried by the phone apps."""
from pathlib import Path
import base64
import re
import struct
import zlib

HEADER = struct.Struct("<4s7I")
LAYOUT = struct.Struct("<8H")
LAYOUT_VALUES = (10, 27, 60, 60, 80, 30, 80, 47)
RAW_BYTES = 60 * 60 * 2
MAX_BYTES = 65520


def source_art(root):
    text = (Path(root) / "include/AlbumArt.h").read_text(encoding="utf-8")
    raw, jpg = [], []
    for name in ("EIGHT", "LOVE", "GOODBYE"):
        def get(kind):
            match = re.search(rf"{kind}_{name}\[\]\s+PROGMEM\s*=\s*\{{(.*?)\}}", text, re.S)
            if not match:
                raise ValueError(f"Missing {kind}_{name}")
            return [int(n) for n in re.findall(r"\d+", match.group(1))]
        pixels = get("ART")
        if len(pixels) != RAW_BYTES // 2 or any(x > 65535 for x in pixels):
            raise ValueError("Invalid raw artwork")
        raw.append(struct.pack(f"<{len(pixels)}H", *pixels))
        jpg.append(bytes(get("JPG")))
    return raw, jpg


def build_package(root):
    raw, jpg = source_art(root)
    payload = LAYOUT.pack(*LAYOUT_VALUES) + b"".join(raw) + b"".join(jpg)
    result = HEADER.pack(b"MGMP", 1, HEADER.size + len(payload),
                         zlib.crc32(payload), *(len(x) for x in jpg), RAW_BYTES) + payload
    if len(result) > MAX_BYTES:
        raise ValueError("Package too large")
    return result


def parse_package(package):
    if len(package) < HEADER.size or len(package) > MAX_BYTES:
        raise ValueError("Invalid package size")
    magic, version, total, crc, j0, j1, j2, raw_size = HEADER.unpack_from(package)
    if (magic != b"MGMP" or version != 1 or total != len(package) or raw_size != RAW_BYTES
            or total != HEADER.size + LAYOUT.size + 3 * RAW_BYTES + j0 + j1 + j2
            or zlib.crc32(package[HEADER.size:]) != crc):
        raise ValueError("Invalid package")
    values = LAYOUT.unpack_from(package, HEADER.size)
    if values != LAYOUT_VALUES:
        raise ValueError("Unsupported screen layout")
    offset = HEADER.size + LAYOUT.size
    raw = [package[offset+i*RAW_BYTES:offset+(i+1)*RAW_BYTES] for i in range(3)]
    offset += 3 * RAW_BYTES
    jpg = []
    for length in (j0, j1, j2):
        jpg.append(package[offset:offset+length])
        offset += length
    return {"art": values[:4], "title": values[4:6], "artist": values[6:]}, raw, jpg


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    package = build_package(root)
    parse_package(package)
    (root / "web/music-pack.js").write_text(
        "// Generated by tools/music_package.py\nwindow.__magooMusicPack='"
        + base64.b64encode(package).decode("ascii") + "';\n", encoding="utf-8")
    print(f"Music package: {len(package)} bytes")
