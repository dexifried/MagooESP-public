"""Bundle the shared dashboard and its existing artwork into Expo Go."""
from pathlib import Path
import base64,json,re,sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from embed_dashboard import render_page

def data_url(data): return 'data:image/jpeg;base64,'+base64.b64encode(data).decode('ascii')
def build_dashboard(root=Path('.')):
 page=render_page(root)
 old="const nativeApp=new URLSearchParams(location.search).get('app')==='1';"
 if page.count(old)!=1:raise ValueError('Dashboard native app marker changed')
 page=page.replace(old,'const nativeApp=true;')
 for name in ('hero','home','speed','navigation','music'):
  page=page.replace("url('/"+name+".jpg')",'url('+data_url((root/'web'/f'{name}.jpg').read_bytes())+')')
 album=(root/'include/AlbumArt.h').read_text(encoding='utf-8')
 images=[]
 for name in ('EIGHT','LOVE','GOODBYE'):
  match=re.search(r'JPG_'+name+r'\[\]\s+PROGMEM\s*=\s*\{(.*?)\}',album,re.S)
  if not match:raise ValueError('Album artwork missing: '+name)
  images.append(data_url(bytes(map(int,re.findall(r'\d+',match.group(1))))))
 page=page.replace('src="/album/0.jpg"','src="'+images[0]+'"')
 old="const albumUrl='/album/'+d.art+'.jpg';"
 if page.count(old)!=1:raise ValueError('Dashboard album artwork marker changed')
 page=page.replace(old,"const albumUrl=window.__magooAlbum[d.art]||window.__magooAlbum[0];")
 addon=(root/'expo-app/web-addon.js').read_text(encoding='utf-8-sig')
 page=page.replace('</body></html>','<script>window.__magooAlbum='+json.dumps(images)+';</script><script>'+addon+'</script></body></html>')
 # The dashboard begins asynchronous work before the appended script executes;
 # define album art before its main script so a fast response cannot race it.
 marker='<script>window.__magooAlbum='+json.dumps(images)+';</script>'
 network=(root/'expo-app/network-web.js').read_text(encoding='utf-8-sig')
 package=(root/'web/music-pack.js').read_text(encoding='utf-8')
 prelude=marker+'<script>'+network+'</script><script>'+package+'</script>'
 page=page.replace(marker,'').replace('<script>\nconst nativeApp=true;',prelude+'<script>\nconst nativeApp=true;')
 if prelude not in page or 'window.__magooApplyLocation' not in page:raise ValueError('Expo injection failed')
 return page

if __name__=='__main__':
 root=Path(__file__).resolve().parents[1]
 (root/'expo-app/dashboard.generated.js').write_text('// Generated by tools/build_expo_dashboard.py; edit web/ instead.\nexport default '+json.dumps(build_dashboard(root),ensure_ascii=True)+';\n',encoding='utf-8')
